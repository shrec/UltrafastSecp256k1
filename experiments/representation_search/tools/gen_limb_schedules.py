#!/usr/bin/env python3
"""Emit the verified limb-level multiply schedules as C++.

    python3 tools/gen_limb_schedules.py > generated_limb_schedules.h

Every schedule is checked against exact integer arithmetic mod p BEFORE it is
emitted, on 94 cases including all-limbs-at-maximum, p and p-1 -- the inputs
that break a carry schedule and that random sampling essentially never
generates. A schedule that fails verification is not written out at all.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from repsearch.fieldkernels import production_mul, wide_mul
from repsearch.modarith import to_cpp, verify

SCHEDULES = [(production_mul, "sched_production"), (wide_mul, "sched_wide")]

if __name__ == "__main__":
    print("// GENERATED by tools/gen_limb_schedules.py -- do not edit, regenerate.")
    print("// EXPERIMENT ONLY (experiments/representation_search). Not production code.")
    print()
    for factory, name in SCHEDULES:
        s = factory()
        ok, msg = verify(s)
        if not ok:
            sys.stderr.write("REFUSING to emit %s: %s\n" % (s.name, msg))
            raise SystemExit(1)
        sys.stderr.write("%-18s verified: %s\n" % (s.name, msg))
        print(to_cpp(s, name))
        print()
