// Limb-level multiply schedules, side by side. EXPERIMENT ONLY.
// The open question: fe52_mul_inner is 228 instructions / 31 multiplies, and at
// ~58 cycles it sits well above the 31-cycle multiply floor. Is the remainder
// the SERIAL carry/fold chain (in which case a schedule with independent
// columns wins despite more instructions) or instruction throughput (in which
// case it loses)? The weighted model prefers production 40.98 to 52.06, but it
// counts instructions, so it is answering the wrong question if the kernel is
// dependency-bound. Only a measurement settles it.
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <ctime>
#include <vector>
#include "secp256k1/field_52.hpp"
// Generated by tools/gen_limb_schedules.py from repsearch/fieldkernels.py.
#include "generated_limb_schedules.h"

using FE = secp256k1::fast::FieldElement52;
static double now_ns(){ timespec t; clock_gettime(CLOCK_MONOTONIC,&t); return t.tv_sec*1e9+t.tv_nsec; }
struct Rng{uint64_t s;Rng(uint64_t x):s(x){}uint64_t n(){s+=0x9E3779B97F4A7C15ULL;uint64_t z=s;
 z=(z^(z>>30))*0xBF58476D1CE4E5B9ULL;z=(z^(z>>27))*0x94D049BB133111EBULL;return z^(z>>31);}};

static uint64_t sink=0;
typedef void (*MulFn)(uint64_t*, const uint64_t*, const uint64_t*);

// The engine's own kernel, reached through the public operator so the real
// fe52_mul_inner is what runs.
static void sched_engine(uint64_t* r, const uint64_t* a, const uint64_t* b) noexcept {
    FE x, y; std::memcpy(x.n, a, 40); std::memcpy(y.n, b, 40);
    FE z = x * y; std::memcpy(r, z.n, 40);
}

struct Stat { double best, second, spread; };
static Stat robust(std::vector<double> v){ std::sort(v.begin(),v.end());
    return Stat{v[0], v.size()>1?v[1]:v[0], (v.back()-v[0])/v[0]*100.0}; }

int main(int argc, char** argv){
    long iters = 200000; int passes = 13;
    for (int i=1;i<argc;++i){
        if(!std::strcmp(argv[i],"--iters")&&i+1<argc) iters=std::atol(argv[++i]);
        else if(!std::strcmp(argv[i],"--passes")&&i+1<argc) passes=std::atoi(argv[++i]);
    }
    Rng rng(0x5EC0256B1ULL);
    uint64_t A[5], B[5];
    for (int i=0;i<5;i++){ A[i]=rng.n() & 0xFFFFFFFFFFFFFull; B[i]=rng.n() & 0xFFFFFFFFFFFFFull; }

    // Correctness first: every schedule must agree with the engine, bit for bit
    // after normalisation, on random and all-max limbs.
    {
        int bad=0;
        for (int t=0;t<64;t++){
            uint64_t x[5],y[5];
            for(int i=0;i<5;i++){ x[i]= t? (rng.n()&0xFFFFFFFFFFFFFull) : 0xFFFFFFFFFFFFFull;
                                  y[i]= t? (rng.n()&0xFFFFFFFFFFFFFull) : 0xFFFFFFFFFFFFFull; }
            uint64_t re[5], rp[5], rw[5];
            sched_engine(re,x,y); sched_production(rp,x,y); sched_wide(rw,x,y);
            FE fe,fp,fw; std::memcpy(fe.n,re,40); std::memcpy(fp.n,rp,40); std::memcpy(fw.n,rw,40);
            fe.normalize(); fp.normalize(); fw.normalize();
            if(!(fe==fp)) { bad++; printf("  MISMATCH production vs engine at t=%d\n",t); break; }
            if(!(fe==fw)) { bad++; printf("  MISMATCH wide vs engine at t=%d\n",t); break; }
        }
        printf("correctness: %s (production + wide vs the engine kernel)\n\n", bad?"FAIL":"PASS");
        if(bad) return 1;
    }

    struct Row { const char* name; MulFn fn; std::vector<double> v; };
    Row rows[] = {
        {"engine fe52_mul_inner", sched_engine, {}},
        {"sched_production (regen)", sched_production, {}},
        {"sched_wide (9 columns)", sched_wide, {}},
    };
    const size_t n = sizeof(rows)/sizeof(rows[0]);

    // warm-up, discarded
    for (size_t k=0;k<n;k++){ uint64_t x[5]; std::memcpy(x,A,40);
        for(long i=0;i<iters/8;i++){ rows[k].fn(x,x,B); } sink+=x[0]; }

    // Rotating order each pass so no schedule sits permanently in a cold slot.
    for (int p=0;p<passes;p++){
        for (size_t j=0;j<n;j++){
            size_t k=(j+(size_t)p)%n;
            uint64_t x[5]; std::memcpy(x,A,40);
            double t0=now_ns();
            for(long i=0;i<iters;i++) rows[k].fn(x,x,B);   // dependent chain
            rows[k].v.push_back((now_ns()-t0)/(double)iters);
            sink += x[0]^x[4];
        }
    }
    printf("%-28s %10s %10s %9s %9s\n","schedule","ns/op","2nd best","spread","vs engine");
    double base=0;
    for(size_t k=0;k<n;k++){ Stat s=robust(rows[k].v); if(!base) base=s.best;
        printf("%-28s %10.4f %10.4f %8.1f%% %+8.2f%%\n", rows[k].name, s.best, s.second,
               s.spread, (s.best-base)/base*100.0); }
    printf("\nsink %016llx\n",(unsigned long long)sink);
    return 0;
}
