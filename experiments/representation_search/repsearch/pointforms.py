def madd_production() -> SLP:
    """in_tree: jac52_add_mixed_inplace -- the "h2-negation" formula.

    The engine deliberately spends one extra multiply to remove one squaring
    AND to turn every X3/Y3 subtraction into an addition, by carrying the sign
    inside H^2.  This is already a sign-placement representation win in
    production, and it is the clearest in-tree evidence that operation counting
    alone does not decide the winner.
    """
    b = Builder("X1", "Y1", "Z1", "X2", "Y2")
    zz = b.sqr("Z1")
    u2 = b.mul("X2", zz)
    s2 = b.mul(b.mul("Y2", zz), "Z1")
    h = b.add(u2, b.neg("X1"))
    z3 = b.mul("Z1", h)
    i = b.add("Y1", b.neg(s2))
    h2 = b.neg(b.sqr(h))                 # -H^2
    i2 = b.sqr(i)
    h3 = b.mul(h2, h)                    # -H^3
    t = b.mul("X1", h2)                  # -X1 H^2
    x3 = b.add(b.add(b.add(i2, h3), t), t)
    tp = b.add(t, x3)
    h3y = b.mul(h3, "Y1")
    y3 = b.add(b.mul(tp, i), h3y)
    return b.build("madd_production", {"X": x3, "Y": y3, "Z": z3},
                   "in_tree: jac52_add_mixed_inplace, h2-negation")


def madd_2007_bl() -> SLP:
    """in_tree (legacy 4x64): jacobian_add_mixed_inplace.  EFD madd-2007-bl."""
    b = Builder("X1", "Y1", "Z1", "X2", "Y2")
    Z1Z1 = b.sqr("Z1")
    U2 = b.mul("X2", Z1Z1)
    S2 = b.mul(b.mul("Y2", "Z1"), Z1Z1)
    H = b.sub(U2, "X1")
    HH = b.sqr(H)
    I = b.mulint(HH, 4)
    J = b.mul(H, I)
    r = b.dbl(b.sub(S2, "Y1"))
    V = b.mul("X1", I)
    x3 = b.sub(b.sub(b.sqr(r), J), b.dbl(V))
    y3 = b.sub(b.mul(r, b.sub(V, x3)), b.dbl(b.mul("Y1", J)))
    z3 = b.sub(b.sub(b.sqr(b.add("Z1", H)), Z1Z1), HH)
    return b.build("madd_2007_bl", {"X": x3, "Y": y3, "Z": z3},
                   "in_tree legacy 4x64: EFD madd-2007-bl")


def madd_2007_bl_zmul() -> SLP:
    """derived: madd-2007-bl with Z3 computed as 2*Z1*H (one multiply) instead
    of (Z1+H)^2 - Z1Z1 - HH (one squaring plus two subtractions)."""
    b = Builder("X1", "Y1", "Z1", "X2", "Y2")
    Z1Z1 = b.sqr("Z1")
    U2 = b.mul("X2", Z1Z1)
    S2 = b.mul(b.mul("Y2", "Z1"), Z1Z1)
    H = b.sub(U2, "X1")
    HH = b.sqr(H)
    I = b.mulint(HH, 4)
    J = b.mul(H, I)
    r = b.dbl(b.sub(S2, "Y1"))
    V = b.mul("X1", I)
    x3 = b.sub(b.sub(b.sqr(r), J), b.dbl(V))
    y3 = b.sub(b.mul(r, b.sub(V, x3)), b.dbl(b.mul("Y1", J)))
    z3 = b.dbl(b.mul("Z1", H))
    return b.build("madd_2007_bl_zmul", {"X": x3, "Y": y3, "Z": z3},
                   "derived: madd-2007-bl with Z3 = 2*Z1*H")


def madd_prod_no_signfold() -> SLP:
    """derived: the production mixed-add WITHOUT the h2-negation trick, so the
    subtractions stay subtractions.  Isolates exactly what the sign placement
    buys, with the multiply/square counts held constant."""
    b = Builder("X1", "Y1", "Z1", "X2", "Y2")
    zz = b.sqr("Z1")
    u2 = b.mul("X2", zz)
    s2 = b.mul(b.mul("Y2", zz), "Z1")
    h = b.sub(u2, "X1")
    z3 = b.mul("Z1", h)
    i = b.sub("Y1", s2)
    h2 = b.sqr(h)
    i2 = b.sqr(i)
    h3 = b.mul(h2, h)
    t = b.mul("X1", h2)
    x3 = b.sub(b.sub(i2, h3), b.dbl(t))
    tp = b.sub(x3, t)          # X3 - X1*H^2  (sign matters: see AUDIT note)
    y3 = b.sub(b.mul(tp, i), b.mul(h3, "Y1"))
    return b.build("madd_prod_no_signfold", {"X": x3, "Y": y3, "Z": z3},
                   "derived: production mixed-add with sign folding removed")


def madd_prod_s2_reassoc() -> SLP:
    """derived: S2 = Y2 * (Z1 * zz) instead of (Y2 * zz) * Z1.

    Pure re-association -- identical multiply count, different dependency
    shape.  Z1*zz = Z1^3 is independent of Y2, so it can start one step
    earlier; this is the kind of change an operation-count model cannot see.
    """
    b = Builder("X1", "Y1", "Z1", "X2", "Y2")
    zz = b.sqr("Z1")
    zzz = b.mul("Z1", zz)
    u2 = b.mul("X2", zz)
    s2 = b.mul("Y2", zzz)
    h = b.add(u2, b.neg("X1"))
    z3 = b.mul("Z1", h)
    i = b.add("Y1", b.neg(s2))
    h2 = b.neg(b.sqr(h))
    i2 = b.sqr(i)
    h3 = b.mul(h2, h)
    t = b.mul("X1", h2)
    x3 = b.add(b.add(b.add(i2, h3), t), t)
    tp = b.add(t, x3)
    h3y = b.mul(h3, "Y1")
    y3 = b.add(b.mul(tp, i), h3y)
    return b.build("madd_prod_s2_reassoc", {"X": x3, "Y": y3, "Z": z3},
                   "derived: ast_precedence_permutation on S2 = Y2*Z1*zz")


