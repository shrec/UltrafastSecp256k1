def mdbl_2007_bl() -> SLP:
    """EFD mdbl-2007-bl with a=0 (Z1 == 1)."""
    b = Builder("X", "Y")
    XX = b.sqr("X")
    YY = b.sqr("Y")
    YYYY = b.sqr(YY)
    S = b.dbl(b.sub(b.sub(b.sqr(b.add("X", YY)), XX), YYYY))
    M = b.mulint(XX, 3)
    T = b.sub(b.sqr(M), b.dbl(S))
    y3 = b.sub(b.mul(M, b.sub(S, T)), b.mulint(YYYY, 8))
    z3 = b.dbl("Y")
    return b.build("mdbl_2007_bl", {"X": T, "Y": y3, "Z": z3},
                   "EFD mdbl-2007-bl, a=0, Z1=1")


