def dbl_production() -> SLP:
    """in_tree: jac52_double_coords (src/cpu/src/point.cpp).

    libsecp256k1 gej_double, a=0 specialisation.
        L = (3/2) X^2,  S = Y^2,  T = -X S
        X3 = L^2 + 2T,  Y3 = -(L (T + X3) + S^2),  Z3 = Y Z
    """
    b = Builder("X", "Y", "Z")
    s = b.sqr("Y")
    l = b.half(b.mulint(b.sqr("X"), 3))
    z3 = b.mul("Z", "Y")
    t = b.mul(b.neg(s), "X")
    x3 = b.add(b.add(b.sqr(l), t), t)
    s2 = b.sqr(s)
    tp = b.add(t, x3)
    y3 = b.neg(b.add(b.mul(tp, l), s2))
    return b.build("dbl_production", {"X": x3, "Y": y3, "Z": z3},
                   "in_tree: jac52_double_coords, libsecp gej_double a=0")


def dbl_2009_l() -> SLP:
    """in_tree (legacy 4x64 path): jacobian_double_inplace.  EFD dbl-2009-l."""
    b = Builder("X", "Y", "Z")
    A = b.sqr("X")
    B = b.sqr("Y")
    C = b.sqr(B)
    tmp = b.sub(b.sub(b.sqr(b.add("X", B)), A), C)
    D = b.dbl(tmp)
    E = b.mulint(A, 3)
    F = b.sqr(E)
    x3 = b.sub(F, b.dbl(D))
    y3 = b.sub(b.mul(E, b.sub(D, x3)), b.mulint(C, 8))
    z3 = b.dbl(b.mul("Y", "Z"))
    return b.build("dbl_2009_l", {"X": x3, "Y": y3, "Z": z3},
                   "in_tree legacy 4x64: EFD dbl-2009-l")


def dbl_2007_bl() -> SLP:
    """EFD dbl-2007-bl with a=0.  Trades multiplications for squarings."""
    b = Builder("X", "Y", "Z")
    XX = b.sqr("X")
    YY = b.sqr("Y")
    YYYY = b.sqr(YY)
    ZZ = b.sqr("Z")
    S = b.dbl(b.sub(b.sub(b.sqr(b.add("X", YY)), XX), YYYY))
    M = b.mulint(XX, 3)
    T = b.sub(b.sqr(M), b.dbl(S))
    x3 = T
    y3 = b.sub(b.mul(M, b.sub(S, T)), b.mulint(YYYY, 8))
    z3 = b.sub(b.sub(b.sqr(b.add("Y", "Z")), YY), ZZ)
    return b.build("dbl_2007_bl", {"X": x3, "Y": y3, "Z": z3},
                   "EFD dbl-2007-bl, a=0")


def dbl_prod_alt_sign() -> SLP:
    """derived: production doubling with the negation moved off the critical
    path -- T kept positive and the sign folded into the final subtraction."""
    b = Builder("X", "Y", "Z")
    s = b.sqr("Y")
    l = b.half(b.mulint(b.sqr("X"), 3))
    z3 = b.mul("Z", "Y")
    u = b.mul(s, "X")                    # U = +X*Y^2   (no negate here)
    x3 = b.sub(b.sqr(l), b.dbl(u))       # X3 = L^2 - 2U
    s2 = b.sqr(s)
    y3 = b.sub(b.mul(b.sub(u, x3), l), s2)   # Y3 = L(U - X3) - S^2
    return b.build("dbl_prod_alt_sign", {"X": x3, "Y": y3, "Z": z3},
                   "derived: sign_placement variant of production doubling")


def dbl_prod_mul_by_3_as_add() -> SLP:
    """derived: 3*X^2 built from adds instead of mul_int, and the half folded
    into a pre-scaled L.  Tests whether mul_int/half are really free."""
    b = Builder("X", "Y", "Z")
    s = b.sqr("Y")
    xx = b.sqr("X")
    l = b.half(b.add(b.dbl(xx), xx))     # (3/2) X^2 via add-add-half
    z3 = b.mul("Z", "Y")
    t = b.mul(b.neg(s), "X")
    x3 = b.add(b.add(b.sqr(l), t), t)
    s2 = b.sqr(s)
    y3 = b.neg(b.add(b.mul(b.add(t, x3), l), s2))
    return b.build("dbl_prod_mul_by_3_as_add", {"X": x3, "Y": y3, "Z": z3},
                   "derived: operation_fusion probe -- mul_int(3) as add chain")


