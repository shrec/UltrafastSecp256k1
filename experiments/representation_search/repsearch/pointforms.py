"""Point formulas as straight-line programs.

Every formula here is either
  (a) transcribed from THIS repository's real source (marked `in_tree`), or
  (b) a published alternative from the Explicit-Formulas Database / literature, or
  (c) a derived representation variant generated by this experiment.

Nothing here is production code.  These SLPs exist to be proven equivalent and
then measured.  Operation counts in the docstrings are DERIVED BY THE COST MODEL
from the SLP itself, never copied from a comment.

Convention: all doubling/addition formulas take Jacobian (X, Y, Z) and return
Jacobian (X, Y, Z).  Two results are "the same point" when they are projectively
equivalent, (X:Y:Z) ~ (L^2 X : L^3 Y : L Z); raw coordinate identity is NOT
required and NOT expected -- different formulas legitimately land on different
representatives of the same projective class.
"""

